/** Writes lib/visual-assets.ts from the PNGs in public/visuals (id, URL and pixel size), so diagrams place assets by their real proportions. Run after generating. */
import {readdir,writeFile} from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
const dir=path.join(process.cwd(),"public","visuals");
const files=(await readdir(dir)).filter(f=>f.endsWith(".png")).sort();
const rows:string[]=[];
for(const f of files){const m=await sharp(path.join(dir,f)).metadata();rows.push(' "'+f.replace(/\.png$/,"")+'":{src:"/visuals/'+f+'",width:'+m.width+',height:'+m.height+'}');}
await writeFile(path.join(process.cwd(),"lib","visual-assets.ts"),
'/** The plan-diagram asset pack (docs/VISUAL_ASSETS.md): pre-rendered transparent PNGs in public/visuals. Generated by scripts/visual-manifest.ts; do not edit by hand. */\n'+
'export type VisualAsset={src:string;width:number;height:number};\n'+
'export const VISUALS:Record<string,VisualAsset>={\n'+rows.join(",\n")+'\n};\n');
console.log(files.length,"assets");
