// Generates app/styles/brand.css and app/styles/brand-fonts.css from brand/tokens.json (light) and
// brand/tokens.dark.json (dark) with Feather's own theme engine. Run with `npm run brand`.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { buildTheme } from "@aleeforoughi/feather-tokens"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const LIGHT = path.join(root, "brand/tokens.json")
const DARK = path.join(root, "brand/tokens.dark.json")
export const OUT_DIR = path.join(root, "app/styles")

const HEADER = `/* GENERATED by scripts/brand.mjs (npm run brand) from brand/tokens.json and brand/tokens.dark.json. Do not edit.
 * Feather's brand CLI themes one token file at a time; Whoush needs a light AND a dark brand pair, so the light
 * theme is emitted as-is and only the root variable block of the dark theme is appended under :root:root.dark, and under
 * .dark.dark.dark for nested always-dark surfaces such as the full-screen media viewer (same specificity, later than
 * Feather's own .dark defaults, so the Whoush dark brand wins there too).
 * See aleeforoughi/feather#1 for why there are two files. */
`

function build(file) {
  const result = buildTheme(JSON.parse(fs.readFileSync(file, "utf8")))
  if (!result.ok) throw new Error(`${path.relative(root, file)} failed Feather's theme engine:\n- ${result.problems.join("\n- ")}`)
  return result
}

/** The first rule of the dark build: `:root:root { ... }`, with the selector scoped to the .dark class. */
export function darkRootBlock(css) {
  const start = css.indexOf(":root:root {")
  if (start === -1) throw new Error("dark theme has no :root:root block")
  const end = css.indexOf("\n}\n", start)
  if (end === -1) throw new Error("dark :root:root block is not closed")
  return css.slice(start, end + 3).replace(":root:root {", ":root:root.dark,\n.dark.dark.dark {")
}

/** Pure: returns the two generated files' contents. */
export function generateBrand() {
  const light = build(LIGHT)
  const dark = build(DARK)
  if (light.fonts !== dark.fonts) throw new Error("light and dark tokens must use the same fonts (brand-fonts.css is shared)")
  const css = `${HEADER}${light.css.trimEnd()}\n\n/* Dark: only the variable block of tokens.dark.json. Density and component rules above are shared. */\n${darkRootBlock(dark.css)}`
  return { "brand.css": css, "brand-fonts.css": light.fonts }
}

export function writeBrand() {
  const files = generateBrand()
  fs.mkdirSync(OUT_DIR, { recursive: true })
  for (const [name, content] of Object.entries(files)) fs.writeFileSync(path.join(OUT_DIR, name), content)
  return Object.keys(files)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const written = writeBrand()
    console.log(`Brand generated: ${written.map((f) => `app/styles/${f}`).join(", ")}`)
  } catch (error) {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  }
}
